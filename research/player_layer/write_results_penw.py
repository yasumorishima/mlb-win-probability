"""Writes RESULTS_PENW_2026.md from published/results_penw_2026.json."""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
r = json.loads((HERE / "published/results_penw_2026.json").read_text())
t, h, a = r["tests"], r["holm_adjusted_p"], r["arms"]
f = lambda x: f"{x:+.6f}"
row = lambda k, name: (f"| {name} | {f(t[k]['mean'])} | {f(t[k]['ci95'][0])} to {f(t[k]['ci95'][1])} | {h[k]:.4f} | "
                       f"**{'SUPPORTED' if r['supported'][k] else 'NOT SUPPORTED'}** |")
L = ["# Results: PENW_RECAL (60-day reliever usage window) on the 2026 regular season", "",
     f"Pre-registration `PREREG_PENW.md` (frozen in `bdac248`, merged `229f9dc`, md5 `{r['frozen']['prereg_md5']}`, no amendments); "
     f"`test_penw_2026.py` (md5 `{r['frozen']['script_md5']}`) run once on 2026-10-28 in a Claude Code cloud session "
     f"(Python {r['versions']['python']}, numpy {r['versions']['numpy']}, pandas {r['versions']['pandas']}); "
     f"all {r['frozen']['n_listed']} frozen md5s matched; the predictions were recomputed from the frozen parts and coefficients.",
     f"{r['n_rows']:,} plate appearances in {r['n_games']:,} games.",
     "Not blind: 2026 was used before in this repository, including PEN_RECAL's own 2026 result (see the PREREG's disclosure).",
     "Generated by `write_results_penw.py` from `published/results_penw_2026.json`.", "",
     "| hypothesis | difference | 95% interval | Holm-adjusted p | verdict |", "|---|---|---|---|---|",
     row("H1_PENW_RECAL_minus_PEN_RECAL", "H1 Brier PENW_RECAL < PEN_RECAL"),
     row("H2_PENW_RECAL_minus_TEAM", "H2 Brier PENW_RECAL < TEAM (consistency check)"), ""]
if r["supported"]["H1_PENW_RECAL_minus_PEN_RECAL"]:
    L += ["H1 is supported. As registered, the look-back view's win probability series becomes PENW_RECAL",
          "(games 2022-2026) and the bullpen mixture in the bench options uses 60-day usage; the usage-pattern",
          "pick (「起用パターン」) stays at 30 days. The gain is small: "
          f"{100 * (a['PEN_RECAL']['brier'] - a['PENW_RECAL']['brier']) / (a['TEAM']['brier'] - a['PEN_RECAL']['brier']):.0f}% "
          "of PEN_RECAL's Brier gain over TEAM on 2026."]
else:
    L += ["H1 is not supported; PEN_RECAL stays."]
L += ["", "## Reported (no test)", "", "| arm | Brier | log loss | WP 0.3-0.5: predicted - observed |", "|---|---|---|---|"]
L += [f"| {k} | {v['brier']:.6f} | {v['log_loss']:.6f} | {v['band_0.3_0.5_gap_pt']:+.2f} pt |" for k, v in a.items()]
L += ["", "PENW is the 60-day layer before the recalibration."]
(HERE / "RESULTS_PENW_2026.md").write_text("\n".join(L) + "\n")
print("\n".join(L))
