"""Writes RESULTS_BLEND_2026.md from published/results_blend_2026.json."""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
r = json.loads((HERE / "published/results_blend_2026.json").read_text())
t, h, a = r["tests"], r["holm_adjusted_p"], r["arms"]
f = lambda x: f"{x:+.5f}"
row = lambda k, name: (f"| {name} | {f(t[k]['mean'])} | {f(t[k]['ci95'][0])} to {f(t[k]['ci95'][1])} | {h[k]:.4f} | "
                       f"**{'SUPPORTED' if r['supported'][k] else 'NOT SUPPORTED'}** |")
L = ["# Results: BLEND on the 2026 regular season", "",
     f"Pre-registration `PREREG_BLEND.md` (frozen in `95a5309`, md5 `{r['frozen']['prereg_md5']}`, no amendments); "
     f"`test_blend_2026.py` (md5 `{r['frozen']['script_md5']}`) run once on 2026-10-28 in a Claude Code cloud session "
     f"(Python {r['versions']['python']}, numpy {r['versions']['numpy']}, pandas {r['versions']['pandas']}); every frozen md5 matched.",
     "Not blind: PLAYER ≈ TEAM on 2026 was known when this test was designed (see the PREREG).",
     "Generated by `write_results_blend.py` from `published/results_blend_2026.json`.", "",
     "| hypothesis | difference | 95% interval | Holm-adjusted p | verdict |", "|---|---|---|---|---|",
     row("H1_BLEND_minus_TEAM", "H1 Brier BLEND < TEAM"), row("H2_BLEND_minus_PLAYER", "H2 Brier BLEND < PLAYER"), "",
     "Neither is supported. As the PREREG expected, one season cannot resolve a gain of this size; this is not",
     "evidence that blending adds nothing. As registered, the app's headline WP stays the team layer.", "",
     "## Reported (no test)", "", "| arm | Brier | log loss | WP 0.3-0.5: predicted - observed |", "|---|---|---|---|"]
L += [f"| {k} | {v['brier']:.6f} | {v['log_loss']:.6f} | {v['band_0.3_0.5_gap_pt']:+.2f} pt |" for k, v in a.items()]
L += ["", "P_RECAL (the player layer recalibrated on out-of-fold 2022-2025 predictions) has the smallest 0.3-0.5 band gap."]
(HERE / "RESULTS_BLEND_2026.md").write_text("\n".join(L) + "\n")
print("\n".join(L))
