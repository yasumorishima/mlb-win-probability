"""Writes RESULTS_2026.md from published/results_2026.json (no number is typed by hand)."""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
r = json.loads((HERE / "published/results_2026.json").read_text())
t, h, a = r["tests"], r["holm_adjusted_p"], r["arms"]
f = lambda x: f"{x:+.5f}"
ci = lambda k: f"{f(t[k]['ci95'][0])} to {f(t[k]['ci95'][1])}"
v = lambda k: "SUPPORTED" if r["supported"][k] else "NOT SUPPORTED"
H1, H2, H3 = "H1_PLAYER_minus_ENGINE_brier", "H2_PLAYER_minus_TEAM_brier", "H3_PLAYER_minus_ENGINE_p1_logloss"
lines = [
    "# Results: player layer v1 on the 2026 regular season",
    "",
    f"Pre-registration: `PREREG.md` (frozen in commit `942b428`, md5 `{r['frozen']['prereg_md5']}`, no amendments).",
    f"`test_2026.py` (md5 `{r['frozen']['script_md5']}`) run once on 2026-10-28 in a Claude Code cloud session",
    f"(Python {r['versions']['python']}, numpy {r['versions']['numpy']}, pandas {r['versions']['pandas']}); every frozen md5 matched.",
    f"Gate before outcomes: {r['gate']['rows']:,} rows; the recomputed engine equals the published `p_ENGINE` on the",
    f"{r['gate']['rows_compared']:,} rows with |score difference| <= 15 (max difference {r['gate']['maxabs_engine_vs_published']}; {r['gate']['rows_abs_diff_over_15']} rows outside).",
    "2026 had been used before in this repository (engine calibration, team layer, steal study); see PREREG.",
    "This file is generated by `write_results.py` from `published/results_2026.json`.",
    "",
    "## Verdict",
    "",
    "| hypothesis | difference | 95% interval | Holm-adjusted p | verdict |",
    "|---|---|---|---|---|",
    f"| H1 Brier PLAYER < ENGINE | {f(t[H1]['mean'])} | {ci(H1)} | {h[H1]:.4f} | **{v(H1)}** |",
    f"| H2 Brier PLAYER < TEAM | {f(t[H2]['mean'])} | {ci(H2)} | {h[H2]:.4f} | **{v(H2)}** |",
    f"| H3 P(>=1 more run this half) log loss PLAYER < ENGINE | {f(t[H3]['mean'])} | {ci(H3)} | {h[H3]:.4f} | **{v(H3)}** |",
    "",
    f"{r['n_rows']:,} plate appearances in {r['n_games']:,} games; H3 on {r['runs']['n']:,} rows ({r['runs']['halves_ended_early']} half ended early left out).",
    "H2 is not supported: on 2026 the player layer and the team layer cannot be told apart by Brier",
    "(the interval covers differences of about +-0.001 either way). This is not evidence that they are equal.",
    "",
    "## Reported (no test)",
    "",
    "| arm | Brier | log loss | WP 0.3-0.5: predicted - observed |",
    "|---|---|---|---|",
] + [f"| {k} | {a[k]['brier']:.6f} | {a[k]['log_loss']:.6f} | {a[k]['band_0.3_0.5_gap_pt']:+.2f} pt (n {a[k]['band_n']:,}) |" for k in a] + [
    "",
    f"P(>=1 more run this half), log loss: PLAYER {r['runs']['PLAYER_logloss']:.5f}, ENGINE {r['runs']['ENGINE_logloss']:.5f} (observed rate {r['runs']['observed_p1']:.4f}).",
    "",
    "Brier by stage (innings 1-3 / 4-6 / 7+):",
    "",
    "| arm | 1-3 | 4-6 | 7+ |",
    "|---|---|---|---|",
] + [f"| {k} | " + " | ".join(f"{r['brier_by_stage'][s][k]:.5f}" for s in ("1-3", "4-6", "7+")) + " |" for k in a] + [
    "",
    "Calibration in tenths for every arm: `published/results_2026.json` (`arms.<arm>.calibration`).",
    "",
    "## What follows (as registered)",
    "",
    "- H1 supported: the player layer becomes the base of the bench screen's numbers, with the disclosure that",
    "  2026 had been used before. The app keeps the frozen engine / team layer for the headline WP until the 2027",
    "  prospective check.",
    "- H2 not supported: both layers stay and are shown with their 2026 numbers.",
    "- 2027: the same frozen code is scored prospectively (rule registered before opening day).",
]
(HERE / "RESULTS_2026.md").write_text("\n".join(lines) + "\n")
print("\n".join(lines))
