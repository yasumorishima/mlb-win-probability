"""Writes RESULTS_PEN_2026.md from published/results_pen_2026.json."""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
r = json.loads((HERE / "published/results_pen_2026.json").read_text())
t, h, a = r["tests"], r["holm_adjusted_p"], r["arms"]
f = lambda x: f"{x:+.5f}"
row = lambda k, name: (f"| {name} | {f(t[k]['mean'])} | {f(t[k]['ci95'][0])} to {f(t[k]['ci95'][1])} | {h[k]:.4f} | "
                       f"**{'SUPPORTED' if r['supported'][k] else 'NOT SUPPORTED'}** |")
L = ["# Results: PEN_RECAL on the 2026 regular season", "",
     f"Pre-registration `PREREG_PEN.md` (frozen in `ae87a76`, merged `fa757a3`, md5 `{r['frozen']['prereg_md5']}`, no amendments); "
     f"`test_pen_2026.py` (md5 `{r['frozen']['script_md5']}`) run once on 2026-10-28 in a Claude Code cloud session "
     f"(Python {r['versions']['python']}, numpy {r['versions']['numpy']}, pandas {r['versions']['pandas']}); "
     f"all {r['frozen']['n_listed']} frozen md5s matched; the predictions were recomputed from the frozen parts and coefficients.",
     f"{r['n_rows']:,} plate appearances in {r['n_games']:,} games.",
     "Not blind: 2026 was used before in this repository (see the PREREG's disclosure (a)-(d)); 2027 is the clean check.",
     "Generated by `write_results_pen.py` from `published/results_pen_2026.json`.", "",
     "| hypothesis | difference | 95% interval | Holm-adjusted p | verdict |", "|---|---|---|---|---|",
     row("H1_PEN_RECAL_minus_TEAM", "H1 Brier PEN_RECAL < TEAM"), row("H2_PEN_RECAL_minus_PLAYER", "H2 Brier PEN_RECAL < PLAYER"), ""]
both = all(r["supported"].values())
L += ["Both are supported. As registered, the look-back view's win probability becomes PEN_RECAL (games 2022-2026,",
      "where usage tables exist); live and the API keep TEAM until a 2027 check."] if both else \
     ["As registered, H1 decides the headline: " + ("supported." if r["supported"]["H1_PEN_RECAL_minus_TEAM"] else "not supported; the headline stays TEAM.")]
L += ["", "## Reported (no test)", "", "| arm | Brier | log loss | WP 0.3-0.5: predicted - observed |", "|---|---|---|---|"]
L += [f"| {k} | {v['brier']:.6f} | {v['log_loss']:.6f} | {v['band_0.3_0.5_gap_pt']:+.2f} pt |" for k, v in a.items()]
L += ["", "PEN is the same layer before the recalibration; the recalibration mainly lowers the 0.3-0.5 band gap."]
(HERE / "RESULTS_PEN_2026.md").write_text("\n".join(L) + "\n")
print("\n".join(L))
