"""Writes RESULTS_PENT_2026.md from published/results_pent_2026.json."""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
r = json.loads((HERE / "published/results_pent_2026.json").read_text())
t, h, a = r["tests"], r["holm_adjusted_p"], r["arms"]
f = lambda x: f"{x:+.6f}"
row = lambda k, name: (f"| {name} | {f(t[k]['mean'])} | {f(t[k]['ci95'][0])} to {f(t[k]['ci95'][1])} | {h[k]:.4f} | "
                       f"**{'SUPPORTED' if r['supported'][k] else 'NOT SUPPORTED'}** |")
L = ["# Results: PENT_RECAL (lead-state smoothing TAU 1) on the 2026 regular season", "",
     f"Pre-registration `PREREG_PENT.md` (frozen in `d4e4e9b`, merged `06b122f`, md5 `{r['frozen']['prereg_md5']}`, no amendments); "
     f"`test_pent_2026.py` (md5 `{r['frozen']['script_md5']}`) run once on 2026-10-28 in a Claude Code cloud session "
     f"(Python {r['versions']['python']}, numpy {r['versions']['numpy']}, pandas {r['versions']['pandas']}); "
     f"all {r['frozen']['n_listed']} frozen md5s matched; the predictions were recomputed from the frozen parts and coefficients.",
     f"{r['n_rows']:,} plate appearances in {r['n_games']:,} games.",
     "Not blind: 2026 was used before in this repository, including the 2026 results of PEN_RECAL, PENW_RECAL and PENR_RECAL (see the PREREG's disclosure).",
     "Generated by `write_results_pent.py` from `published/results_pent_2026.json`.", "",
     "| hypothesis | difference | 95% interval | Holm-adjusted p | verdict |", "|---|---|---|---|---|",
     row("H1_PENT_RECAL_minus_PENR_RECAL", "H1 Brier PENT_RECAL < PENR_RECAL"),
     row("H2_PENT_RECAL_minus_TEAM", "H2 Brier PENT_RECAL < TEAM (consistency check)"), ""]
if r["supported"]["H1_PENT_RECAL_minus_PENR_RECAL"]:
    L += ["H1 is supported. As registered, the look-back view's win probability series becomes PENT_RECAL",
          "(games 2022-2026) and the bench options' bullpen mixture uses TAU 1. The game notes already written",
          "are not regenerated; the usage-pattern pick is unchanged.",
          "Gain: " f"{100 * (a['PENR_RECAL']['brier'] - a['PENT_RECAL']['brier']) / (a['TEAM']['brier'] - a['PENR_RECAL']['brier']):.0f}% "
          "of PENR_RECAL's Brier gain over TEAM on 2026."]
else:
    L += ["H1 is not supported; PENR_RECAL stays."]
L += ["", "## Reported (no test)", "", "| arm | Brier | log loss | WP 0.3-0.5: predicted - observed |", "|---|---|---|---|"]
L += [f"| {k} | {v['brier']:.6f} | {v['log_loss']:.6f} | {v['band_0.3_0.5_gap_pt']:+.2f} pt |" for k, v in a.items()]
L += ["", "PENT is the layer before the recalibration."]
(HERE / "RESULTS_PENT_2026.md").write_text("\n".join(L) + "\n")
print("\n".join(L))
