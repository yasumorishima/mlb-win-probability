"""Writes RESULTS_PENR_2026.md from published/results_penr_2026.json."""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
r = json.loads((HERE / "published/results_penr_2026.json").read_text())
t, h, a = r["tests"], r["holm_adjusted_p"], r["arms"]
f = lambda x: f"{x:+.6f}"
row = lambda k, name: (f"| {name} | {f(t[k]['mean'])} | {f(t[k]['ci95'][0])} to {f(t[k]['ci95'][1])} | {h[k]:.4f} | "
                       f"**{'SUPPORTED' if r['supported'][k] else 'NOT SUPPORTED'}** |")
L = ["# Results: PENR_RECAL (bullpen roles refined: five lead states, KAPPA 0.25) on the 2026 regular season", "",
     f"Pre-registration `PREREG_PENR.md` (frozen in `09d78c6`, merged `d3118af`, md5 `{r['frozen']['prereg_md5']}`, no amendments); "
     f"`test_penr_2026.py` (md5 `{r['frozen']['script_md5']}`) run once on 2026-10-28 in a Claude Code cloud session "
     f"(Python {r['versions']['python']}, numpy {r['versions']['numpy']}, pandas {r['versions']['pandas']}); "
     f"all {r['frozen']['n_listed']} frozen md5s matched; the predictions were recomputed from the frozen parts and coefficients.",
     f"{r['n_rows']:,} plate appearances in {r['n_games']:,} games.",
     "Not blind: 2026 was used before in this repository, including PEN_RECAL's and PENW_RECAL's 2026 results (see the PREREG's disclosure).",
     "Generated by `write_results_penr.py` from `published/results_penr_2026.json`.", "",
     "| hypothesis | difference | 95% interval | Holm-adjusted p | verdict |", "|---|---|---|---|---|",
     row("H1_PENR_RECAL_minus_PENW_RECAL", "H1 Brier PENR_RECAL < PENW_RECAL"),
     row("H2_PENR_RECAL_minus_TEAM", "H2 Brier PENR_RECAL < TEAM (consistency check)"), ""]
if r["supported"]["H1_PENR_RECAL_minus_PENW_RECAL"]:
    L += ["H1 is supported. As registered, the look-back view's win probability series becomes PENR_RECAL",
          "(games 2022-2026). The bench options' bullpen mixture and the usage-pattern pick are unchanged by this test.",
          "H1 tests the setting as a whole (five lead states and KAPPA 0.25); in the sizing most of the gain came from KAPPA.",
          "Gain: " f"{100 * (a['PENW_RECAL']['brier'] - a['PENR_RECAL']['brier']) / (a['TEAM']['brier'] - a['PENW_RECAL']['brier']):.0f}% "
          "of PENW_RECAL's Brier gain over TEAM on 2026. The 0.3-0.5 band gap is slightly larger than PENW_RECAL's (reported, not tested)."]
else:
    L += ["H1 is not supported; PENW_RECAL stays."]
L += ["", "## Reported (no test)", "", "| arm | Brier | log loss | WP 0.3-0.5: predicted - observed |", "|---|---|---|---|"]
L += [f"| {k} | {v['brier']:.6f} | {v['log_loss']:.6f} | {v['band_0.3_0.5_gap_pt']:+.2f} pt |" for k, v in a.items()]
L += ["", "PENR is the layer before the recalibration."]
(HERE / "RESULTS_PENR_2026.md").write_text("\n".join(L) + "\n")
print("\n".join(L))
